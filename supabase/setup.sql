create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.payment_profiles (
  id uuid primary key default gen_random_uuid(),
  label text not null unique default 'principal',
  payer_name text not null,
  payer_email text not null,
  payer_document varchar(14) not null,
  payer_phone varchar(15),
  is_active boolean not null default true,
  usage_count bigint not null default 0,
  last_used_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint payment_profiles_valid_document check (payer_document ~ '^[0-9]{11}$' or payer_document ~ '^[0-9]{14}$'),
  constraint payment_profiles_valid_phone check (payer_phone is null or payer_phone ~ '^[0-9]{10,15}$')
);

drop trigger if exists trg_payment_profiles_updated_at on public.payment_profiles;
create trigger trg_payment_profiles_updated_at before update on public.payment_profiles
for each row execute function public.set_updated_at();

create table if not exists public.donations (
  id uuid primary key default gen_random_uuid(),
  external_id text not null unique,
  transaction_id text unique,
  amount numeric(12,2) not null check (amount >= 5),
  fee numeric(12,2),
  status text not null default 'CREATING'
    check (status in ('CREATING','PENDING','COMPLETED','FAILED','REFUNDED','CHARGEBACK')),
  donor_name text,
  donor_email text,
  donor_document_last4 varchar(4),
  public_name text,
  show_public boolean not null default false,
  display_mode text not null default 'none' check (display_mode in ('supporter','popup','none')),
  qrcode_emv text,
  utm_source text,
  utm_medium text,
  utm_campaign text,
  utm_content text,
  utm_term text,
  platform varchar(32) not null default 'BRAVOPAY',
  gateway_payload jsonb not null default '{}'::jsonb,
  payment_profile_id uuid references public.payment_profiles(id),
  requester_hash text,
  generation_key text,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists trg_donations_updated_at on public.donations;
create trigger trg_donations_updated_at before update on public.donations
for each row execute function public.set_updated_at();

create unique index if not exists donations_generation_key_unique_idx on public.donations(generation_key) where generation_key is not null;
create index if not exists donations_status_created_idx on public.donations(status, created_at desc);
create index if not exists donations_requester_created_idx on public.donations(requester_hash, created_at desc) where requester_hash is not null;
create index if not exists donations_display_mode_paid_idx on public.donations(display_mode, paid_at desc) where status = 'COMPLETED';

create table if not exists public.webhook_events (
  id bigint generated by default as identity primary key,
  event_id text not null unique,
  event_type text not null,
  transaction_id text not null,
  external_id text,
  status text not null,
  payload jsonb not null,
  received_at timestamptz not null default now()
);

create table if not exists public.payment_generation_audit (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('CREATED','REUSED','BLOCKED','FAILED')),
  external_id text,
  amount numeric(12,2),
  payment_profile_id uuid references public.payment_profiles(id),
  requester_hash text not null,
  user_agent_hash text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists payment_generation_audit_requester_idx on public.payment_generation_audit(requester_hash, created_at desc);

drop function if exists public.claim_payment_profile();

create function public.claim_payment_profile()
returns table (id uuid, payer_name text, payer_email text, payer_document text, payer_phone text)
language plpgsql security definer set search_path = public as $$
declare selected_id uuid;
begin
  select p.id into selected_id
  from public.payment_profiles p
  where p.is_active = true
  order by p.usage_count asc, p.last_used_at asc nulls first, p.created_at asc
  for update skip locked limit 1;

  if selected_id is null then return; end if;

  update public.payment_profiles
  set usage_count = usage_count + 1, last_used_at = now(), updated_at = now()
  where payment_profiles.id = selected_id;

  return query
  select p.id, p.payer_name, p.payer_email, p.payer_document::text, p.payer_phone::text
  from public.payment_profiles p where p.id = selected_id;
end;
$$;

alter table public.payment_profiles enable row level security;
