revoke all on function public.claim_payment_profile() from public, anon, authenticated;
grant execute on function public.claim_payment_profile() to service_role;

create table if not exists public.supporter_like_totals (
  supporter_key text primary key,
  like_count smallint not null default 0,
  updated_at timestamptz not null default now(),
  constraint supporter_like_totals_key_length
    check (char_length(supporter_key) between 1 and 160),
  constraint supporter_like_totals_count_range
    check (like_count between 0 and 50)
);

create table if not exists public.supporter_like_votes (
  supporter_key text not null
    references public.supporter_like_totals(supporter_key)
    on delete cascade,
  voter_hash text not null,
  created_at timestamptz not null default now(),
  primary key (supporter_key, voter_hash),
  constraint supporter_like_votes_hash_length
    check (char_length(voter_hash) between 32 and 128)
);

create index if not exists supporter_like_votes_voter_idx
on public.supporter_like_votes (voter_hash);

drop function if exists public.set_supporter_like(text, text, boolean);

create function public.set_supporter_like(
  p_supporter_key text,
  p_voter_hash text,
  p_liked boolean
)
returns table (
  liked boolean,
  like_count integer,
  max_reached boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  current_count integer := 0;
  already_liked boolean := false;
begin
  p_supporter_key := trim(coalesce(p_supporter_key, ''));
  p_voter_hash := trim(coalesce(p_voter_hash, ''));

  if char_length(p_supporter_key) < 1 or char_length(p_supporter_key) > 160 then
    raise exception 'supporter_key inválida';
  end if;

  if char_length(p_voter_hash) < 32 or char_length(p_voter_hash) > 128 then
    raise exception 'voter_hash inválido';
  end if;

  insert into public.supporter_like_totals (
    supporter_key,
    like_count,
    updated_at
  )
  values (
    p_supporter_key,
    0,
    now()
  )
  on conflict (supporter_key) do nothing;

  select total.like_count
  into current_count
  from public.supporter_like_totals as total
  where total.supporter_key = p_supporter_key
  for update;

  select exists (
    select 1
    from public.supporter_like_votes as vote
    where vote.supporter_key = p_supporter_key
      and vote.voter_hash = p_voter_hash
  )
  into already_liked;

  if p_liked then
    if already_liked then
      return query
      select true, current_count, current_count >= 50;
      return;
    end if;

    if current_count >= 50 then
      return query
      select false, 50, true;
      return;
    end if;

    insert into public.supporter_like_votes (
      supporter_key,
      voter_hash
    )
    values (
      p_supporter_key,
      p_voter_hash
    );

    update public.supporter_like_totals as total
    set
      like_count = least(50, total.like_count + 1),
      updated_at = now()
    where total.supporter_key = p_supporter_key
    returning total.like_count
    into current_count;

    return query
    select true, current_count, current_count >= 50;
    return;
  end if;

  if already_liked then
    delete from public.supporter_like_votes as vote
    where vote.supporter_key = p_supporter_key
      and vote.voter_hash = p_voter_hash;

    update public.supporter_like_totals as total
    set
      like_count = greatest(0, total.like_count - 1),
      updated_at = now()
    where total.supporter_key = p_supporter_key
    returning total.like_count
    into current_count;
  end if;

  return query
  select false, current_count, current_count >= 50;
end;
$$;

alter table public.supporter_like_totals enable row level security;
alter table public.supporter_like_votes enable row level security;

revoke all on table public.supporter_like_totals from public, anon, authenticated;
revoke all on table public.supporter_like_votes from public, anon, authenticated;
